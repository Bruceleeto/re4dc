#!/usr/bin/env python3
"""Import supplied custom artwork and encode the generated Luis sheet as native assets.

This is an offline source-asset compiler; the game never opens/resizes PNGs.
Input handoff files are read-only. Luis's head crop is fit to 32x27 within
48x27. The blink takes the generated eyelids only; all other native pixels are
identical. Re-running the same inputs must reproduce the byte arrays.
"""
import argparse, hashlib, json, shutil
from pathlib import Path

def main():
    p=argparse.ArgumentParser();p.add_argument('handoff',type=Path);p.add_argument('luis_sheet',type=Path)
    a=p.parse_args();root=Path(__file__).resolve().parents[1]
    out=root/'game/vmu_assets';out.mkdir(exist_ok=True)
    for name in ('re4_vmu_assets.h','re4_vmu_leon.h'):
        shutil.copyfile(a.handoff/'include'/name,out/name)
    glyphs=json.loads((a.handoff/'assets/sprites.json').read_text())['font']['glyphs']
    text='// Supplied handoff font; generated by export_vmu_context.py.\nstruct FontGlyph { char ch; unsigned char width, rows[5]; };\nstatic const FontGlyph kFont[]={\n'
    for ch,g in glyphs.items():
        text+="    {'%s',%d,{%s}},\n"%(ch,g['width'],','.join(str(int(r,2)) for r in g['rows']))
    (out/'font.inc').write_text(text+'};\n')
    # Decode the generated source directly to the fixed binary representation.
    from PIL import Image
    im=Image.open(a.luis_sheet).convert('L');w,h=im.size
    # Shared head crop for both source panels, with their exact relative framing.
    bounds=[]
    for side in (0,1):
        box=im.crop((side*w//2,0,(side+1)*w//2,h)).point(lambda v:255 if v<128 else 0).getbbox()
        bounds.append(box)
    left=min(b[0] for b in bounds);top=min(b[1] for b in bounds)
    right=max(b[2] for b in bounds);bottom=max(b[3] for b in bounds)
    panels=[]
    for side in (0,1):
        rows=[]
        for y in range(27):
            row=[0]*48
            for x in range(32):
                # Area average avoids fragile selection of single dithering pixels.
                x0=side*w//2+left+x*(right-left)//32;x1=side*w//2+left+(x+1)*(right-left)//32
                y0=top+y*(bottom-top)//27;y1=top+(y+1)*(bottom-top)//27
                values=list(im.crop((x0,y0,x1,y1)).getdata())
                row[x+8]=int(sum(values)<128*len(values))
            rows.append(row)
        panels.append(rows)
    # One blink, no drifting head, hair, collar or silhouette.
    blink=[r.copy() for r in panels[0]]
    for y in range(11,17):
        for x in range(18,36):blink[y][x]=panels[1][y][x]
    panels[1]=blink
    text='// Luis Sera: generated source sheet, compiled to canonical row-major MSB bits.\n'
    native={}
    for name,rows in zip(('Neutral','Blink'),panels):
        bits=bytes(sum(rows[y][x+b]<<(7-b) for b in range(8)) for y in range(27) for x in range(0,48,8))
        text+='static const uint8_t kLuis%s[162]={\n'%name
        text+='\n'.join('    '+','.join('0x%02x'%v for v in bits[i:i+12])+',' for i in range(0,162,12))+'\n};\n'
        native[name]={'rows':[''.join(map(str,r)) for r in rows],'sha256':hashlib.sha256(bits).hexdigest()}
    (out/'luis.inc').write_text(text)
    (out/'luis.json').write_text(json.dumps(native,indent=2)+'\n')
    # Preserve the generation source locally for review and reproducible import.
    shutil.copyfile(a.luis_sheet,out/'luis-source.png')
    provenance={'handoff_manifest_sha256':hashlib.sha256((a.handoff/'MANIFEST.sha256').read_bytes()).hexdigest(),
      'luis_source_sha256':hashlib.sha256(a.luis_sheet.read_bytes()).hexdigest(),'encoding':'48x27, row-major MSB, 1=ink',
      'luis_generation':'Built-in image_gen, 2026-10-12. Luis Sera 2005, neutral/blink, binary pixel art matching supplied Ashley/Hunnigan; see VMU implementation report for prompt.'}
    (out/'provenance.json').write_text(json.dumps(provenance,indent=2)+'\n')
    frames=json.loads((a.handoff/'reference/golden-frames.json').read_text())
    frames['frames']=[f for f in frames['frames'] if f['display']!='monster']
    tests=root/'tests/vmu';tests.mkdir(parents=True,exist_ok=True)
    (tests/'golden-docked.json').write_text(json.dumps(frames,indent=2)+'\n')
    print('Imported exact supplied assets; encoded 2 Luis frames; retained',len(frames['frames']),'docked goldens')
if __name__=='__main__':main()

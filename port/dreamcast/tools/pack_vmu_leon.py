#!/usr/bin/env python3
"""Pack the Leon growth frames (game/vmu_assets/re4_vmu_leon.h) for the Dreamcast image.

    python3 pack_vmu_leon.py [header] [out.inc]

The header stores four 48x27 frames at six bytes per row (648 B). The renderer reads only the growth region
x=30..47, y=7..25 (bytes 3..5 of rows 7..25) and stage 0 (CLEAR) is empty, so the image keeps stages 1..3 of that
region: 3 x 19 x 3 = 171 B. Deterministic offline conversion; the renderer's golden frames prove it lossless.
"""
import re
import sys
from pathlib import Path

game = Path(__file__).resolve().parents[1] / "game"
src = Path(sys.argv[1]) if len(sys.argv) > 1 else game / "vmu_assets/re4_vmu_leon.h"
dst = Path(sys.argv[2]) if len(sys.argv) > 2 else game / "vmu_assets/re4_vmu_leon_packed.inc"
text = src.read_text()
body = text[text.index("RE4_VMU_LEON_GROWTH_FRAMES"):]
values = [int(v, 16) for v in re.findall(r"0x([0-9A-Fa-f]{2})", body[: body.index(";")])]
assert len(values) == 4 * 162, len(values)
frames = [values[i * 162:(i + 1) * 162] for i in range(4)]
for y in range(27):  # nothing outside the region, stage 0 empty
    for b in range(6):
        for s in range(4):
            v = frames[s][y * 6 + b]
            inside = 7 <= y <= 25 and b >= 3
            if not inside:
                assert v == 0, (s, y, b)
            elif b == 3:
                assert v & 0xFC == 0, (s, y, b)
assert not any(frames[0])
out = ["/* Generated by tools/pack_vmu_leon.py from re4_vmu_leon.h. Do not edit by hand.",
       " * [stage-1][y-7][byte-3]: stages 1..3, rows 7..25, bytes 3..5 (x 24..47; ink only at x >= 30). */",
       "static const uint8_t RE4_VMU_LEON_GROWTH_PACKED[3][19][3] = {"]
for s in range(1, 4):
    rows = []
    for y in range(7, 26):
        rows.append("{" + ",".join("0x%02X" % frames[s][y * 6 + b] for b in range(3, 6)) + "}")
    out.append(" {" + ",".join(rows) + "},")
out.append("};")
dst.write_text("\n".join(out) + "\n")
print(dst)
